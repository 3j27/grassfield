// Settings > Keyboard: the Grassfield-owned keyboard.lua (ADR-0031 amendment), next to mouse-trackpad.lua, a Lua chunk returning
// plain values that config/hypr/grassfield/input.lua reads (and checks again) after Omarchy's keyboard defaults and before the
// user's own input.lua. It holds only what the user chose: without a key, the session's value stays. Also the xkb layouts of
// /usr/share/X11/xkb/rules/base.lst for Input Sources. Pure functions, unit-tested (tests/unit/tst_settingskeyboard.qml).

// The stops of the two sliders (macOS: 8 for the rate, Off first, 6 for the delay, Long first). Omarchy's 40 and 250 are stops.
var RATES = [0, 2, 5, 10, 15, 25, 40, 60];
var DELAYS = [1800, 1400, 1000, 600, 400, 250];
// The session's values when keyboard.lua does not set them (Omarchy's default.hypr.input, and omarchy.lua's fallback).
var SESSION_RATE = 40;
var SESSION_DELAY = 250;
var MAX_LAYOUTS = 4;

function nearestIndex(list, value) {
    let best = 0;
    for (let i = 1; i < list.length; i++) {
        if (Math.abs(list[i] - value) < Math.abs(list[best] - value))
            best = i;
    }
    return best;
}

function validLayout(s) {
    return typeof s === "string" && /^[a-z][a-z0-9_-]*$/.test(s) && s.length <= 16;
}

function validVariant(s) {
    return s === "" || (typeof s === "string" && /^[a-z0-9][a-z0-9_-]*$/.test(s) && s.length <= 32);
}

// Value of `key = <literal>` in the generated chunk, or undefined.
function field(text, key) {
    const m = new RegExp("^\\s*" + key + "\\s*=\\s*([^,\\n]+?)\\s*,?\\s*$", "m").exec(text);
    return m ? m[1] : undefined;
}

// Value of `key = "<text>"` in the generated chunk (a comma-separated list stays whole), or undefined.
function stringField(text, key) {
    const m = new RegExp("^\\s*" + key + "\\s*=\\s*\"([^\"\\n]*)\"\\s*,?\\s*$", "m").exec(text);
    return m ? m[1] : undefined;
}

// The choices the file holds ({rate, delay, sources: [{layout, variant}]}, each absent when the file does not set it), with the
// rules of input.lua: a rate 0-100, a delay 100-3000, 1 to 4 layouts with their variants.
function parse(text) {
    const out = {};
    if (typeof text !== "string")
        return out;
    const rate = field(text, "repeat_rate");
    if (rate !== undefined && /^\d{1,3}$/.test(rate) && Number(rate) <= 100)
        out.rate = Number(rate);
    const delay = field(text, "repeat_delay");
    if (delay !== undefined && /^\d{3,4}$/.test(delay) && Number(delay) >= 100 && Number(delay) <= 3000)
        out.delay = Number(delay);
    const lay = stringField(text, "kb_layout");
    if (lay !== undefined) {
        const layouts = lay.split(",");
        const v = stringField(text, "kb_variant");
        // As input.lua: variants that do not fit (another count, a bad name) are dropped, the layouts stay.
        let variants = layouts.map(() => "");
        if (v !== undefined && v.split(",").length === layouts.length && v.split(",").every(validVariant))
            variants = v.split(",");
        if (layouts.length <= MAX_LAYOUTS && layouts.every(validLayout))
            out.sources = layouts.map((l, i) => ({layout: l, variant: variants[i]}));
    }
    return out;
}

// The file's text for the choices (only the keys they hold); "" when they hold none (the page then writes nothing new).
function serialize(choices) {
    const c = choices || {};
    const lines = [];
    if (Number.isInteger(c.rate) && c.rate >= 0 && c.rate <= 100)
        lines.push("  repeat_rate = " + c.rate + ",");
    if (Number.isInteger(c.delay) && c.delay >= 100 && c.delay <= 3000)
        lines.push("  repeat_delay = " + c.delay + ",");
    const sources = Array.isArray(c.sources) ? c.sources.filter(s => s && validLayout(s.layout) && validVariant(s.variant || "")) : [];
    if (sources.length > 0 && sources.length <= MAX_LAYOUTS) {
        lines.push("  kb_layout = \"" + sources.map(s => s.layout).join(",") + "\",");
        lines.push("  kb_variant = \"" + sources.map(s => s.variant || "").join(",") + "\",");
    }
    return "-- Generated by Grassfield Settings (Keyboard). Settings rewrites this file; the compositor reads it after Omarchy's\n"
        + "-- keyboard defaults and before your own ~/.config/hypr/input.lua, which wins over it.\n"
        + "return {\n" + lines.map(l => l + "\n").join("") + "}\n";
}

// The session's layout without keyboard.lua: XKBLAYOUT and XKBVARIANT of /etc/vconsole.conf (what Omarchy reads), else "us".
function sessionSources(vconsole) {
    let layout = "us", variant = "";
    for (const line of String(vconsole).split("\n")) {
        const m = /^\s*([A-Za-z_]+)\s*=\s*"?([^"#\s]*)"?/.exec(line);
        if (m && m[1] === "XKBLAYOUT" && m[2] !== "")
            layout = m[2];
        else if (m && m[1] === "XKBVARIANT")
            variant = m[2];
    }
    const layouts = layout.split(","), variants = variant.split(",");
    return layouts.filter(validLayout).map((l, i) => ({layout: l, variant: validVariant(variants[i] || "") ? (variants[i] || "") : ""}));
}

// xkb's base.lst: {names: {"fr": "French", "fr:bepo": "French (BEPO)"}, all: [{layout, variant, name}] sorted by name}.
function parseLayouts(text) {
    const names = {};
    const all = [];
    let section = "";
    for (const line of String(text).split("\n")) {
        const head = /^!\s*(\w+)/.exec(line);
        if (head) {
            section = head[1];
            continue;
        }
        if (section === "layout") {
            const m = /^\s+(\S+)\s+(.+?)\s*$/.exec(line);
            if (m && validLayout(m[1])) {
                names[m[1]] = m[2];
                all.push({layout: m[1], variant: "", name: m[2]});
            }
        } else if (section === "variant") {
            const m = /^\s+(\S+)\s+([a-z][a-z0-9_-]*):\s+(.+?)\s*$/.exec(line);
            if (m && validVariant(m[1]) && validLayout(m[2])) {
                names[m[2] + ":" + m[1]] = m[3];
                all.push({layout: m[2], variant: m[1], name: m[3]});
            }
        }
    }
    all.sort((a, b) => a.name.localeCompare(b.name));
    return {names: names, all: all};
}

// The name of a source, else its xkb codes.
function sourceName(source, names) {
    const key = source.variant ? source.layout + ":" + source.variant : source.layout;
    return (names && names[key]) || key;
}

// Layouts that cannot type Latin letters: the list of Omarchy's default/hypr/input.lua, as config/hypr/grassfield/input.lua
// keeps it (tests/shell/session_input.sh compares the three). Hyprland resolves the key bindings against the first layout, and
// a session starts in it (a Latin password at the lock screen), so a Latin one is always first (macOS keeps a Latin input
// source too).
var NON_LATIN = ["af", "am", "ara", "bd", "bg", "by", "et", "ge", "gr", "il", "in", "iq", "ir", "kg", "kh", "kz", "la", "lk", "mk",
    "mm", "mn", "mv", "np", "rs", "ru", "sy", "th", "tj", "ua"];

function latin(layout) {
    return NON_LATIN.indexOf(layout) < 0;
}

// The sources with a Latin one first, as input.lua applies them: the first Latin source moves to the front, else U.S. is added
// before the others (at most MAX_LAYOUTS).
function latinFirst(sources) {
    const list = Array.isArray(sources) ? sources.slice() : [];
    if (list.length > 0 && latin(list[0].layout))
        return list;
    const at = list.findIndex(s => latin(s.layout));
    if (at > 0)
        return [list[at]].concat(list.filter((s, i) => i !== at));
    return [{layout: "us", variant: ""}].concat(list).slice(0, MAX_LAYOUTS);
}
