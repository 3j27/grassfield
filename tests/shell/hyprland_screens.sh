#!/usr/bin/env bash
# ADR-0035 D-1: Hyprland's own update and donation windows stay off in a Grassfield session. The session config sets
# ecosystem.no_update_news = true (no "Hyprland Updated" window) and ecosystem.no_donation_nag = true (no donation window)
# itself, after the Omarchy include, so they hold when that include fails or Omarchy's envs.lua changes them; the nested dev
# session gets the same values from the same file. ecosystem.enforce_permissions is never set by Grassfield: Hyprland's
# default (off) applies and an opt-in (Omarchy, the user's input.lua) wins. The welcome tour needs a config marked
# `autogenerated = true`, which no Grassfield file is.
# The Lua part runs session.lua and dev.lua with a plain Lua interpreter against a stub of Hyprland's `hl` table, with a
# `require` that behaves like Hyprland's (an error inside a module becomes a config error and require returns an empty
# table; only a module that cannot be found raises: Hyprland 0.56.2 src/config/lua/ConfigManager.cpp:312-377, installed as
# the global `require` at :548-553), and fixture Omarchy trees. Needs `lua`; skipped without it, like
# tests/shell/session_input.sh. The text checks need nothing. It also guards ADR-0001's fallback: session.lua must load
# without Omarchy (`just check-config` runs Hyprland's own check that way too).
set -euo pipefail
root=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
tmp=$(mktemp -d "${GRASSFIELD_TEST_TMP:-${TMPDIR:-/tmp}}/hyprland-screens.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
fail=0
check() { if "$@"; then echo "PASS: $desc"; else echo "FAIL: $desc"; fail=1; fi; }

desc="no Grassfield Hyprland file marks the config autogenerated (Hyprland's welcome tour, hyprland-welcome)"
check bash -c '! grep -rnE "^[^-]*autogenerated[[:space:]]*=" "$1/config/hypr" --include="*.lua"' _ "$root"

desc="no Grassfield Hyprland file sets enforce_permissions: Hyprland's default applies and an opt-in wins"
check bash -c '! grep -rnE "^[^-]*enforce_permissions[[:space:]]*=" "$1/config/hypr" --include="*.lua"' _ "$root"

desc="dev.lua sets no ecosystem key of its own: a nested run shows the real session's values"
check bash -c '! grep -nE "^[^-]*ecosystem[[:space:]]*=" "$1/config/hypr/dev.lua"' _ "$root"

desc="session.lua loads the Omarchy include before grassfield.core (whose looknfeel.lua sets the ecosystem keys)"
check bash -c 'o=$(grep -n "require(\"grassfield.omarchy\")" "$1/config/hypr/session.lua" | head -n1 | cut -d: -f1)
  c=$(grep -n "require(\"grassfield.core\")" "$1/config/hypr/session.lua" | head -n1 | cut -d: -f1)
  l=$(grep -n "require(\"grassfield.looknfeel\")" "$1/config/hypr/grassfield/core.lua" | head -n1 | cut -d: -f1)
  [[ -n $o && -n $c && -n $l && $o -lt $c ]]' _ "$root"

if ! command -v lua >/dev/null; then
  echo "SKIP: no Lua interpreter (session.lua and dev.lua not evaluated)"
  exit "$fail"
fi

cat >"$tmp/case.lua" <<'LUA'
-- usage: lua case.lua <session|dev|stub> <repo root>
-- Prints the effective value of each ecosystem key (the last one any hl.config call set, as Hyprland applies them), the
-- number of calls that set one, the config errors Hyprland would list, and what the Omarchy include reported.
local which, repo = arg[1], arg[2]
local configs, config_errors = {}, {}
local function proxy()
  return setmetatable({}, { __index = function() return proxy() end, __call = function() return proxy() end })
end
hl = setmetatable({
  config = function(t) configs[#configs + 1] = t end,
  on = function() end,  -- start callbacks never run here
}, { __index = function() return proxy() end })

-- Hyprland's require (safeLuaRequire): a module that cannot be found raises, as plain Lua does; any other error inside the
-- module is added to the config errors and require returns an empty table, remembered in package.loaded.
local plain_require = require
local include  -- what grassfield.omarchy returned (core.lua clears package.loaded["grassfield.*"] afterwards)
require = function(name, ...)
  local res = table.pack(pcall(plain_require, name, ...))
  if res[1] then
    if name == "grassfield.omarchy" then include = res[2] end
    return table.unpack(res, 2, res.n)
  end
  local err = tostring(res[2])
  local not_found = "module '" .. tostring(name) .. "' not found"
  if err:sub(1, #not_found) == not_found then error(err, 0) end
  config_errors[#config_errors + 1] = 'require("' .. tostring(name) .. '"): ' .. err
  local fallback = {}
  package.loaded[name] = fallback
  return fallback
end

if which == "stub" then
  -- The stub itself: a missing module raises, a failing one does not.
  package.preload["failing.module"] = function() error("boom") end
  print("missing_raises", tostring(not pcall(require, "no.such.module")))
  local ok, value = pcall(require, "failing.module")
  print("failing_returns_table", tostring(ok and type(value) == "table"), "errors", #config_errors)
  return
end

local path = repo .. "/config/hypr/" .. which .. ".lua"
local ok, err = pcall(dofile, path)
print("loaded", tostring(ok), ok and "" or tostring(err))
local final, writers = {}, {}
for i, c in ipairs(configs) do
  if type(c.ecosystem) == "table" then
    writers[#writers + 1] = i
    for k, v in pairs(c.ecosystem) do final[k] = v end
  end
end
for _, k in ipairs({ "no_update_news", "no_donation_nag", "enforce_permissions" }) do print(k, tostring(final[k])) end
print("writers", #writers)
print("config_errors", #config_errors)
for _, e in ipairs(config_errors) do print("config_error", e) end
print("include_ok", type(include) == "table" and tostring(include.ok) or "none")
LUA

screens_off() { # screens_off <output>: no update news, no donation window
  grep -qx 'no_update_news	true' <<<"$1" && grep -qx 'no_donation_nag	true' <<<"$1"
}

out=$(cd "$tmp" && lua "$tmp/case.lua" stub "$root" 2>&1)
desc="the stub's require behaves like Hyprland's: a missing module raises"
check grep -qx 'missing_raises	true' <<<"$out"
desc="the stub's require behaves like Hyprland's: a failing module becomes one config error and returns a table"
check grep -qx 'failing_returns_table	true	errors	1' <<<"$out"

# An Omarchy tree whose envs.lua turns both windows back on and opts in to Hyprland's permission prompts.
mkdir -p "$tmp/omarchy/default/hypr" "$tmp/broken/default/hypr" "$tmp/home" "$tmp/none"
printf 'o = o or {}\n' >"$tmp/omarchy/default/hypr/helpers.lua"
printf 'hl.config({ ecosystem = { no_update_news = false, no_donation_nag = false, enforce_permissions = true } })\n' \
  >"$tmp/omarchy/default/hypr/envs.lua"
# An Omarchy whose envs.lua fails (a broken update).
printf 'o = o or {}\n' >"$tmp/broken/default/hypr/helpers.lua"
printf 'error("broken envs.lua")\n' >"$tmp/broken/default/hypr/envs.lua"
run() { # run <session|dev> <omarchy path>
  (cd "$tmp" && env -i PATH="$PATH" HOME="$tmp/home" OMARCHY_PATH="$2" GRASSFIELD_CONFIG_DIR="$root/config/hypr" \
    XDG_RUNTIME_DIR="$tmp" lua "$tmp/case.lua" "$1" "$root" 2>&1)
}

out=$(run session "$tmp/omarchy")
desc="session.lua with an Omarchy that turns the windows back on: update news and donation window still off"
check screens_off "$out"
desc="session.lua with that Omarchy: its opt-in to Hyprland's permission prompts is kept (Grassfield does not override it)"
check grep -qx 'enforce_permissions	true' <<<"$out"
desc="session.lua with that Omarchy: the whole config loads, no config error, Omarchy's call and Grassfield's set ecosystem keys"
check bash -c 'grep -qx "loaded	true	" <<<"$1" && grep -qx "config_errors	0" <<<"$1" && grep -qx "writers	2" <<<"$1"' _ "$out"

out=$(run session "$tmp/none")
desc="session.lua without Omarchy: the include reports the failure and the config still loads (guard_path is defined first)"
check bash -c 'grep -qx "include_ok	false" <<<"$1" && grep -qx "loaded	true	" <<<"$1" && grep -qx "config_errors	0" <<<"$1"' _ "$out"
desc="session.lua without Omarchy: both windows off, enforce_permissions left at Hyprland's default"
check bash -c 'grep -qx "no_update_news	true" <<<"$1" && grep -qx "no_donation_nag	true" <<<"$1" && grep -qx "enforce_permissions	nil" <<<"$1"' _ "$out"

out=$(run session "$tmp/broken")
desc="session.lua with a failing envs.lua: Hyprland lists one config error and the include goes on (it does not return early)"
check bash -c 'grep -qx "config_errors	1" <<<"$1" && grep -q "^config_error	require(\"default.hypr.envs\"): " <<<"$1" && grep -qx "include_ok	true" <<<"$1"' _ "$out"
desc="session.lua with a failing envs.lua: the config loads and both windows are off"
check bash -c 'grep -qx "loaded	true	" <<<"$1" && grep -qx "no_update_news	true" <<<"$1" && grep -qx "no_donation_nag	true" <<<"$1"' _ "$out"

out=$(run dev "$tmp/none")
desc="dev.lua (nested session): both windows off, enforce_permissions left at Hyprland's default"
check bash -c 'grep -qx "no_update_news	true" <<<"$1" && grep -qx "no_donation_nag	true" <<<"$1" && grep -qx "enforce_permissions	nil" <<<"$1"' _ "$out"
desc="dev.lua: looknfeel.lua is the only call that sets ecosystem keys"
check grep -qx 'writers	1' <<<"$out"

exit "$fail"
