TEST(Store, DedupeMovesToTheTop)
{
    Store s;
    EXPECT_TRUE(s.add(textItem(idOf(1), QStringLiteral("one"), 100)).added);
    EXPECT_TRUE(s.add(textItem(idOf(2), QStringLiteral("two"), 200)).added);
    const Store::AddResult r = s.add(textItem(idOf(3), QStringLiteral("one"), 300));
    EXPECT_FALSE(r.added);
    EXPECT_EQ(r.id, idOf(1));
    EXPECT_EQ(s.history().first().id, idOf(1));
    EXPECT_EQ(s.history().first().copiedAtMs, 300);
    EXPECT_EQ(s.history().size(), 2);
}

