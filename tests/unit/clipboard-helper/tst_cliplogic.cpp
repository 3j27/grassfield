TEST(Store, HistoryLimits)
{
    Store s;
    for (int i = 1; i <= kHistoryItems + 5; ++i)
        s.add(textItem(idOf(i), QStringLiteral("item %1").arg(i), i));
    EXPECT_EQ(s.history().size(), kHistoryItems);
    EXPECT_FALSE(s.find(idOf(1))) << "the oldest went first";
    EXPECT_TRUE(s.find(idOf(kHistoryItems + 5)));

    Store b;
    Item big;
    big.kind = Kind::Image;
    for (int i = 1; i <= 5; ++i) {
        Item it = big;
        it.id = idOf(i);
        it.parts = {{"image/png", QByteArray(15 * 1024 * 1024, char(i))}};
        it.hash = hashOf(Kind::Image, it.parts.first().data);
        it.copiedAtMs = i;
        const Store::AddResult r = b.add(it);
        if (i == 5) {
            EXPECT_EQ(r.evicted, QList<QByteArray>{idOf(1)});
        }
    }
    EXPECT_LE(b.historyBytes(), kHistoryBytes);
}

TEST(Store, PinLimitsAndUnpin)
{
    Store s;
    for (int i = 1; i <= kPinnedItems + 1; ++i)
        s.add(textItem(idOf(i), QStringLiteral("p %1").arg(i), i));
    for (int i = 1; i <= kPinnedItems; ++i)
        ASSERT_EQ(s.pin(idOf(i), 1000 + i), Store::PinResult::Pinned);
    EXPECT_EQ(s.pin(idOf(kPinnedItems + 1), 5000), Store::PinResult::Full);
    EXPECT_EQ(s.pin(idOf(1), 5000), Store::PinResult::AlreadyPinned);
    EXPECT_EQ(s.pin(idOf(999), 5000), Store::PinResult::NotFound);
    EXPECT_EQ(s.pinnedItems().first().id, idOf(kPinnedItems)) << "newest pin first";

    bool found = false;
    s.unpin(idOf(3), &found);
    EXPECT_TRUE(found);
    EXPECT_FALSE(s.find(idOf(3))->pinned());
    EXPECT_EQ(s.history().last().id, idOf(3)) << "back at its copy time";

    Store bytes;
    Item a;
    a.kind = Kind::Image;
    a.id = idOf(1);
    a.parts = {{"image/png", QByteArray(16 * 1024 * 1024, 'a')}};
    a.hash = "a";
    Item c = a;
    c.id = idOf(2);
    c.hash = "c";
    Item d = a;
    d.id = idOf(3);
    d.hash = "d";
    bytes.add(a);
    bytes.add(c);
    bytes.add(d);
    EXPECT_EQ(bytes.pin(idOf(1), 1), Store::PinResult::Pinned);
    EXPECT_EQ(bytes.pin(idOf(2), 2), Store::PinResult::Pinned);
    EXPECT_EQ(bytes.pin(idOf(3), 3), Store::PinResult::Full) << "32 MiB of pins";
}

TEST(Store, RetentionAndClocks)
{
    Store s;
    const qint64 hour = 3600 * 1000;
    s.add(textItem(idOf(1), QStringLiteral("old"), 0, "boot-a", 0));
    s.add(textItem(idOf(2), QStringLiteral("new"), 7 * hour, "boot-a", 7 * hour));
    s.add(textItem(idOf(3), QStringLiteral("pinned"), 0, "boot-a", 0));
    s.pin(idOf(3), 1);
    EXPECT_EQ(s.expire(8 * hour + 1, 8 * hour + 1, "boot-a", 8 * hour), QList<QByteArray>{idOf(1)});
    EXPECT_TRUE(s.find(idOf(3))) << "pins never expire";

    // Wall clock set back an hour on the same boot: the boot clock still counts the time.
    Store back;
    back.add(textItem(idOf(1), QStringLiteral("a"), 10 * hour, "boot-a", 1000));
    EXPECT_EQ(back.expire(9 * hour, 1000 + 8 * hour + 1, "boot-a", 8 * hour), QList<QByteArray>{idOf(1)});

    // Another boot: the boot clock means nothing; a time in the future is expired at once.
    Store other;
    other.add(textItem(idOf(1), QStringLiteral("a"), 10 * hour, "boot-a", 5 * hour));
    other.add(textItem(idOf(2), QStringLiteral("b"), 9 * hour, "boot-a", 9 * hour));
    EXPECT_EQ(other.expire(9 * hour + 10, 0, "boot-b", 8 * hour), QList<QByteArray>{idOf(1)});
    EXPECT_TRUE(other.find(idOf(2)));

    EXPECT_EQ(clampRetention(1), kMinRetentionMs);
    EXPECT_EQ(clampRetention(kMaxRetentionMs * 2), kMaxRetentionMs);
}

TEST(Store, SearchAndClear)
{
    Store s;
    s.add(textItem(idOf(1), QString::fromUtf8("Café crème"), 1));
    s.add(textItem(idOf(2), QStringLiteral("cafe noir"), 2));
    s.add(textItem(idOf(3), QStringLiteral("tea"), 3));
    s.pin(idOf(1), 10);
    EXPECT_EQ(s.search(QStringLiteral("CAFE")), (QList<QByteArray>{idOf(1), idOf(2)})) << "pins first";
    EXPECT_EQ(s.search(QStringLiteral(" ")).size(), 3);
    EXPECT_EQ(s.clearHistory(), (QList<QByteArray>{idOf(3), idOf(2)}));
    EXPECT_EQ(s.ordered().size(), 1) << "Clear History spares pins";
    EXPECT_EQ(s.clearPinned(), QList<QByteArray>{idOf(1)});
    EXPECT_TRUE(s.ordered().isEmpty());
}

TEST(Store, Touch)
{
    Store s;
    s.add(textItem(idOf(1), QStringLiteral("a"), 1));
    s.add(textItem(idOf(2), QStringLiteral("b"), 2));
    EXPECT_TRUE(s.touch(idOf(1), 50, 50, "boot-a"));
    EXPECT_EQ(s.history().first().id, idOf(1));
    s.pin(idOf(2), 3);
    EXPECT_FALSE(s.touch(idOf(2), 60, 60, "boot-a")) << "a pin stays where it is";
}

TEST(Protocol, EscapeRoundTrip)
{
    const QByteArray raw = "a\\b\nc\rd\x1f" "e";
    const QByteArray esc = escape(raw);
    EXPECT_FALSE(esc.contains('\n'));
    EXPECT_FALSE(esc.contains('\x1f'));
    EXPECT_EQ(unescape(esc), raw);
    const QList<QByteArray> f = splitLine("I\x1f" + escape(QByteArray("x\x1fy")) + "\x1f" + escape(QByteArray("z\\n")));
    EXPECT_EQ(f, (QList<QByteArray>{"I", "x\x1fy", "z\\n"}));
}

