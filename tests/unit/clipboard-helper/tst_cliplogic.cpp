TEST(Text, TitleAndExcerptHideControls)
{
    // A right-to-left override would make "txt.exe" read "exe.txt"; zero-width and control characters go too.
    const QString hiddenChars = QStringLiteral("\n  \n") + QChar(0x202e) + QStringLiteral("abc") + QChar(0x200b) + QChar(0x07)
        + QStringLiteral("def  \nnext");
    EXPECT_EQ(titleOf(hiddenChars), QStringLiteral("abcdef"));
    const QString long1 = QString(kTitleChars - 1, QLatin1Char('a')) + QString::fromUtf8("😀");
    EXPECT_EQ(titleOf(long1).size(), kTitleChars - 1) << "a surrogate pair is never cut in half";
    const QString e = excerptOf(QStringLiteral("line 1\nline 2\x01"));
    EXPECT_EQ(e, QStringLiteral("line 1\nline 2"));
    EXPECT_LE(excerptOf(QString(5000, QLatin1Char('x'))).size(), kExcerptChars);
}

