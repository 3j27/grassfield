-- Input defaults (ADR-0002) and the user's Mouse, Trackpad and Keyboard choices (GF-066, ADR-0031 amendment). The keyboard's
-- defaults (layout from /etc/vconsole.conf, compose:caps, repeat rate and delay, numlock) are set by omarchy.lua, which loads
-- Omarchy's default.hypr.input (or reproduces it); this file sets a kb_* or repeat_* key only when the user chose it in
-- Settings > Keyboard (keyboard.lua below), never numlock.
--
-- Order (macOS: the Mouse and Trackpad settings belong to the user): omarchy.lua applies this file AFTER Omarchy's input
-- defaults and BEFORE the user's own ~/.config/hypr/input.lua, so anything the user writes there wins over Grassfield's
-- defaults. Settings > Mouse and Settings > Trackpad write the Grassfield-owned file below; it is read here, after the
-- packaged defaults, and also before the user's input.lua.
--
-- Grassfield-owned file: $GRASSFIELD_CONFIG_HOME or $XDG_CONFIG_HOME/grassfield (else ~/.config/grassfield) /
-- mouse-trackpad.lua, generated by Settings, a Lua chunk returning a table of plain values (read as text, never run:
-- read_table takes its `key = value` pairs, so nothing in it can run or stall):
--   sensitivity          number -1..1   tracking speed (0 = default), mouse and trackpad
--   natural_scroll       boolean        trackpad scroll direction
--   mouse_natural_scroll boolean        mouse wheel direction
--   tap_to_click         boolean
--   secondary_click      "two_finger" | "corner"   (clickfinger_behavior true | false: bottom-right corner area)
--   gesture_spaces       boolean        swipe left or right with three fingers between Spaces (bindings.lua)
--   gesture_overview     boolean        swipe up and down with three fingers for the Overview
--   gesture_apps         boolean        pinch with the thumb and three fingers for Apps
--
-- Settings > Keyboard writes keyboard.lua next to it, the same kind of chunk; only the keys it holds are applied:
--   repeat_rate          integer 0..100     repeats per second (0: keys do not repeat)
--   repeat_delay         integer 100..3000  milliseconds before a held key repeats
--   kb_layout            "us" or "us,fr"    1 to 4 xkb layouts
--   kb_variant           ",bepo"            one field per layout, each empty or an xkb variant
-- A Latin layout always comes first (M.latin_first, Omarchy's guard: the bindings resolve against the first layout).
-- With two layouts or more, Ctrl+Space selects the next one (xkb grp:ctrl_space_toggle, added to Omarchy's own options).
-- The shell reads the configuration again when either file changes (shell/platform/SessionConfig.qml), so a choice applies
-- at once.

local M = {}

M.defaults = {
  sensitivity = 0,
  natural_scroll = true,
  mouse_natural_scroll = false,
  tap_to_click = true,
  secondary_click = "two_finger",
  gesture_spaces = true,
  gesture_overview = true,
  gesture_apps = true,
}

-- Omarchy's keyboard options (default.hypr.input, and omarchy.lua's fallback), kept when Ctrl+Space is added.
M.kb_options = "compose:caps,shift:both_capslock_cancel"

local function config_file(name)
  local dev = os.getenv("GRASSFIELD_CONFIG_HOME")
  if dev and dev ~= "" then return dev .. "/" .. name end
  local xdg = os.getenv("XDG_CONFIG_HOME")
  local base = (xdg and xdg ~= "") and xdg or ((os.getenv("HOME") or "") .. "/.config")
  return base .. "/grassfield/" .. name
end

function M.path()
  return config_file("mouse-trackpad.lua")
end

function M.keyboard_path()
  return config_file("keyboard.lua")
end

-- The values of a file Settings generates, read as text and never run (review of 2026-10-26: a chunk run even in an empty
-- environment could stall the compositor while it reads its configuration, with `while true do end`): `key = value` pairs
-- whose value is a number, true, false or a double-quoted string without escapes. At most 64 KiB is read; block and line
-- comments are dropped (found as plain text); each line is read alone (a line longer than 200 characters is skipped) with
-- anchored patterns, so a file of any content is read in linear time. nil when the file cannot be opened.
local MAX_LINE = 200

local function read_table(path)
  local f = path and io.open(path, "r")
  if not f then return nil end
  local text = f:read(65536) or ""
  f:close()
  local kept, pos = {}, 1
  while true do
    local open = text:find("--[[", pos, true)
    if not open then
      kept[#kept + 1] = text:sub(pos)
      break
    end
    kept[#kept + 1] = text:sub(pos, open - 1)
    local close = text:find("]]", open + 4, true)
    if not close then break end
    pos = close + 2
  end
  local out = {}
  -- A copy of the loop variable is changed, never the variable itself: Hyprland runs Lua 5.5, where a for-loop variable
  -- is const (assigning to it is a compile error that drops the whole module).
  for raw in table.concat(kept, "\n"):gmatch("[^\n]+") do
    local line = raw
    local comment = line:find("--", 1, true)
    if comment then line = line:sub(1, comment - 1) end
    if #line <= MAX_LINE then
      -- The strings are set aside first (text inside one is never taken for a pair, a comma in one splits nothing), then
      -- each item between commas and braces is matched whole: every pattern here is anchored or starts with a literal.
      local strings = {}
      line = line:gsub('"([^"\\]*)"', function(v)
        strings[#strings + 1] = v
        return "\1" .. #strings .. "\1"
      end)
      for item in line:gmatch("[^,{};]+") do
        local key, value = item:match("^%s*([%a_][%w_]*)%s*=%s*(%S+)%s*$")
        if key then
          local n = value:match("^\1(%d+)\1$")
          if n then
            out[key] = strings[tonumber(n)]
          elseif value == "true" or value == "false" then
            out[key] = value == "true"
          elseif value:match("^%-?%d+%.?%d*$") then
            out[key] = tonumber(value)
          end
        end
      end
    end
  end
  return out
end

-- Layouts that cannot type Latin letters: the list of Omarchy's default/hypr/input.lua (Omarchy 4.0.4; omarchy.lua's
-- fallback and Settings' Keyboard.js keep the same one, tests/shell/session_input.sh compares them). Hyprland resolves the
-- key bindings against the first layout of kb_layout, not the one in use, so with a non-Latin layout first the Super
-- bindings stop working, and a session that starts in it cannot type a Latin password at the lock screen.
M.non_latin = " af am ara bd bg by et ge gr il in iq ir kg kh kz la lk mk mm mn mv np rs ru sy th tj ua "

function M.latin(layout)
  return not M.non_latin:find(" " .. layout .. " ", 1, true)
end

-- The layouts (and their variants, one field each) with a Latin one first, as Settings' Input Sources keeps them (macOS
-- always keeps a Latin input source): the first Latin layout of the list moves to the front, else U.S. is added before the
-- others, as Omarchy does (at most four: xkb has four groups). Returns kb_layout, kb_variant and the number of layouts.
function M.latin_first(kb_layout, kb_variant)
  local layouts, variants = {}, {}
  for field in (kb_layout .. ","):gmatch("([^,]*),") do layouts[#layouts + 1] = field end
  for field in (kb_variant .. ","):gmatch("([^,]*),") do variants[#variants + 1] = field end
  if not M.latin(layouts[1]) then
    local at
    for i, layout in ipairs(layouts) do
      if M.latin(layout) then at = i break end
    end
    if at then
      table.insert(layouts, 1, table.remove(layouts, at))
      table.insert(variants, 1, table.remove(variants, at))
    else
      table.insert(layouts, 1, "us")
      table.insert(variants, 1, "")
      layouts[5], variants[5] = nil, nil
    end
  end
  return table.concat(layouts, ","), table.concat(variants, ","), #layouts
end

local function whole(v, lo, hi)
  return type(v) == "number" and v == math.floor(v) and v >= lo and v <= hi
end

-- The keyboard choices the file holds, each checked; unknown or invalid entries are left out (the session's value stays).
function M.keyboard(path)
  local out = {}
  local saved = read_table(path or M.keyboard_path())
  if not saved then return out end
  if whole(saved.repeat_rate, 0, 100) then out.repeat_rate = saved.repeat_rate end
  if whole(saved.repeat_delay, 100, 3000) then out.repeat_delay = saved.repeat_delay end
  local layouts = 0
  if type(saved.kb_layout) == "string" and #saved.kb_layout <= 64 then
    local good = true
    for field in (saved.kb_layout .. ","):gmatch("([^,]*),") do
      layouts = layouts + 1
      if not field:match("^[a-z][a-z0-9_-]*$") then good = false end
    end
    if good and layouts >= 1 and layouts <= 4 then out.kb_layout = saved.kb_layout else layouts = 0 end
  end
  if out.kb_layout and type(saved.kb_variant) == "string" and #saved.kb_variant <= 128 then
    local fields, good = 0, true
    for field in (saved.kb_variant .. ","):gmatch("([^,]*),") do
      fields = fields + 1
      if field ~= "" and not field:match("^[a-z0-9][a-z0-9_-]*$") then good = false end
    end
    if good and fields == layouts then out.kb_variant = saved.kb_variant end
  end
  if out.kb_layout and not out.kb_variant then
    out.kb_variant = string.rep(",", layouts - 1)
  end
  if out.kb_layout then
    out.kb_layout, out.kb_variant, layouts = M.latin_first(out.kb_layout, out.kb_variant)
  end
  if layouts >= 2 then
    out.kb_options = M.kb_options .. ",grp:ctrl_space_toggle"
  end
  return out
end

-- The user's saved values over the defaults; invalid or unknown entries are ignored (the default stays).
function M.settings(path)
  local out = {}
  for k, v in pairs(M.defaults) do out[k] = v end
  local saved = read_table(path or M.path())
  if not saved then return out end
  if type(saved.sensitivity) == "number" and saved.sensitivity >= -1 and saved.sensitivity <= 1 then
    out.sensitivity = saved.sensitivity
  end
  for _, k in ipairs({ "natural_scroll", "mouse_natural_scroll", "tap_to_click", "gesture_spaces", "gesture_overview", "gesture_apps" }) do
    if type(saved[k]) == "boolean" then out[k] = saved[k] end
  end
  if saved.secondary_click == "two_finger" or saved.secondary_click == "corner" then
    out.secondary_click = saved.secondary_click
  end
  return out
end

function M.apply(path, keyboard_path)
  local s = M.settings(path)
  local k = M.keyboard(keyboard_path)
  if next(k) ~= nil then
    hl.config({ input = k })
  end
  hl.config({
    input = {
      -- Click to focus keyboard; pointer focus (scrolling, hover) follows the mouse, like macOS.
      follow_mouse = 2,
      float_switch_override_focus = 0,
      mouse_refocus = false,
      sensitivity = s.sensitivity,
      natural_scroll = s.mouse_natural_scroll,
      touchpad = {
        natural_scroll = s.natural_scroll,
        clickfinger_behavior = s.secondary_click == "two_finger",
        tap_to_click = s.tap_to_click,
        scroll_factor = 0.5,
      },
    },
  })
  return s
end

M.apply()
return M
