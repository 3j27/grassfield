// Generator of ui/Grassfield/Ui/GraphemeData.js (scripts/dev/gen-glyph-tables.sh): the classes of every code point for the
// symbol rule, taken from FolderStyleLogic::glyphClasses (apps/files/src/folderstylelogic.cpp), so the QML side
// (FolderStyle.js) runs the same algorithm over the same data as Files (C++). Output: runs [first, last, mask, ...] of
// consecutive code points with the same non-zero mask. The Hangul syllable block (U+AC00..U+D7A3) is computed by both
// sides, not listed.
#include "folderstylelogic.h"

#include <QCoreApplication>
#include <cstdio>

int main(int argc, char **argv)
{
    QCoreApplication app(argc, argv);
    std::printf("// Generated by scripts/dev/gen-glyph-tables.sh from FolderStyleLogic::glyphClasses (Qt %s); do not edit.\n", qVersion());
    std::printf(".pragma library\n\n");
    std::printf("// Runs [first, last, mask, ...] of code points with one class mask (GlyphClass bits, apps/files/src/folderstylelogic.h).\n");
    std::printf("const CLASSES = [");
    int column = 120;
    uint start = 0;
    unsigned current = 0;
    auto put = [&](uint lo, uint hi, unsigned mask) {
        char buf[48];
        const int len = std::snprintf(buf, sizeof buf, "0x%X, 0x%X, 0x%X, ", lo, hi, mask);
        if (column + len > 118) {
            std::printf("\n    ");
            column = 4;
        }
        std::printf("%s", buf);
        column += len;
    };
    for (uint cp = 0; cp <= 0x110000; ++cp) {
        const unsigned mask = cp < 0x110000 && !(cp >= 0xAC00 && cp <= 0xD7A3) ? FolderStyleLogic::glyphClasses(cp) : 0;
        if (mask != current) {
            if (current != 0)
                put(start, cp - 1, current);
            start = cp;
            current = mask;
        }
    }
    std::printf("\n];\n");
    return 0;
}
