#!/usr/bin/env bash
# Interim build of grassfield-compositor without CMake/Ninja (not installed yet; see README.md).
# Writes the same outputs as the CMake build: build/grassfield-compositor.so, build/grassfield-compositor-tests
# and build/compile_commands.json (for clang-tidy, gate Q1).
# Usage: compositor/build-direct.sh [plugin|tests|compdb|all|tidy]   (default: all = plugin + tests + compdb)
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build
what=${1:-all}

core_srcs=(src/core/Protocol.cpp src/core/TitlebarLayout.cpp src/core/PointerGesture.cpp src/core/Minimize.cpp src/core/Appmenu.cpp)
glue_srcs=(src/main.cpp src/Titlebar.cpp src/Ipc.cpp src/Minimize.cpp src/AppmenuServer.cpp)
plugin_srcs=("${glue_srcs[@]}" "${core_srcs[@]}")
test_srcs=(tests/ProtocolTest.cpp tests/TitlebarLayoutTest.cpp tests/PointerGestureTest.cpp tests/MinimizeTest.cpp tests/AppmenuTest.cpp)

# Wayland protocol server code generated by hyprwayland-scanner (as Hyprland does for its own protocols):
# build/protocols/appmenu.{hpp,cpp} from protocols/appmenu.xml (org_kde_kwin_appmenu, version 2).
# Regenerated when an output is missing, EMPTY or older than the XML: an unclean shutdown can leave zero-size files
# behind, which a timestamp check alone takes for up to date (the next build then failed).
protocols() {
  mkdir -p build/protocols
  local f stale=0
  for f in build/protocols/appmenu.cpp build/protocols/appmenu.hpp; do
    if [[ ! -s $f || protocols/appmenu.xml -nt $f ]]; then
      stale=1
    fi
  done
  if ((stale)); then
    rm -f build/protocols/appmenu.cpp build/protocols/appmenu.hpp
    hyprwayland-scanner protocols/appmenu.xml build/protocols
    for f in build/protocols/appmenu.cpp build/protocols/appmenu.hpp; do
      [[ -s $f ]] || { echo "build-direct: hyprwayland-scanner left $f missing or empty" >&2; exit 1; }
    done
  fi
}

# Lua symbols are resolved at load time from Hyprland's own liblua (5.5): only Lua's headers are needed.
# shellcheck disable=SC2207
plugin_flags=(-std=c++23 -O2 -g -DNDEBUG -fPIC -Wall -Wextra -Ibuild $(pkg-config --cflags hyprland pixman-1 libdrm) $(pkg-config --cflags lua))
# shellcheck disable=SC2207
plugin_libs=($(pkg-config --libs hyprland pixman-1 libdrm))
# Pure logic only (src/core): no Hyprland headers, no compositor needed.
# shellcheck disable=SC2207
test_flags=(-std=c++23 -O0 -g -Wall -Wextra -Isrc $(pkg-config --cflags gtest_main))
# shellcheck disable=SC2207
test_libs=($(pkg-config --libs gtest_main))

if [[ $what == plugin || $what == all ]]; then
  protocols
  # Generated code: its own object, symbols hidden (no clash with a Hyprland that ships the same interface).
  g++ "${plugin_flags[@]}" -fvisibility=hidden -w -c build/protocols/appmenu.cpp -o build/protocols/appmenu.o
  g++ "${plugin_flags[@]}" -shared "${plugin_srcs[@]}" build/protocols/appmenu.o "${plugin_libs[@]}" -o build/grassfield-compositor.so
fi

if [[ $what == tests || $what == all ]]; then
  g++ "${test_flags[@]}" "${test_srcs[@]}" "${core_srcs[@]}" "${test_libs[@]}" -o build/grassfield-compositor-tests
fi

# One compile command per translation unit, with the exact flags used above.
if [[ $what == compdb || $what == all || $what == tidy ]]; then
  protocols
  entry() { # <source> <flags...>   (arguments go through stdin: jq would parse "-std=..." as its own options)
    local src=$1
    shift
    printf '%s\n' g++ "$@" -c "$src" | jq -R . | jq -s --arg d "$PWD" --arg f "$PWD/$src" '{directory: $d, file: $f, arguments: .}'
  }
  {
    for src in "${plugin_srcs[@]}"; do entry "$src" "${plugin_flags[@]}"; done
    for src in "${test_srcs[@]}"; do entry "$src" "${test_flags[@]}"; done
  } | jq -s . > build/compile_commands.json
fi

# Gate Q1: clang-tidy over the glue and the core (config: .clang-tidy; analyzer findings are errors).
# Generated protocol code is not linted (its header is outside the HeaderFilterRegex).
if [[ $what == tidy ]]; then
  clang-tidy -p build --quiet "${plugin_srcs[@]}" "${test_srcs[@]}"
fi
